
-- ============================================
-- NORTHWIND SOURCE-TO-TARGET MAPPING ANALYSIS
-- ============================================

-- 1. SOURCE PRODUCTS TABLE
USE Northwind;
GO

SELECT
    COLUMN_NAME,
    DATA_TYPE,
    IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'dbo'
  AND TABLE_NAME = 'Products'
ORDER BY ORDINAL_POSITION;


-- 2. STAGING PRODUCTS TABLE
USE NorthwindIntegration;
GO

SELECT
    COLUMN_NAME,
    DATA_TYPE,
    CHARACTER_MAXIMUM_LENGTH,
    NUMERIC_PRECISION,
    NUMERIC_SCALE,
    IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'staging'
  AND TABLE_NAME = 'Products'
ORDER BY ORDINAL_POSITION;


-- 3. CLEANED PRODUCTS TABLE
USE NorthwindIntegration;
GO

SELECT
    COLUMN_NAME,
    DATA_TYPE,
    IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'cleaned'
  AND TABLE_NAME = 'Products'
ORDER BY ORDINAL_POSITION;
